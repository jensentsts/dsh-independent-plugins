import { readFile, writeFile } from 'node:fs/promises'
const root = new URL('./', import.meta.url)
let source = ''
for (const file of ['audio.mjs', 'client-entry.mjs']) {
  const text = (await readFile(new URL(file, root), 'utf8')).replace(/^import .+\r?\n/gmu, '').replace(/^export /gmu, '')
  source += `\n// ${file}\n${text}`
}
const en = JSON.parse(await readFile(new URL('locale/en.json', root), 'utf8'))
const zh = JSON.parse(await readFile(new URL('locale/zh.json', root), 'utf8'))
const output = `// Generated by build.mjs.\nwindow.__ModuleLoader__.load({ id: 'dsh-conversation-audio', factory(require) {\nconst React = require('react');\nconst en = ${JSON.stringify(en)};\nconst zh = ${JSON.stringify(zh)};\n${source}\nreturn { inject, apply };\n} });\n`
await writeFile(new URL('client.js', root), output)
