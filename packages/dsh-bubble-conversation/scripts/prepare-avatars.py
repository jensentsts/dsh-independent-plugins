"""Crop the generated 4x2 sheet into bounded local avatars; never fetch or regenerate artwork."""
from pathlib import Path
import argparse
import base64
import hashlib
import json
import shutil
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
FAMILIES = ['deepseek', 'gpt', 'claude', 'grok', 'glm', 'kimi', 'gemini', 'doubao']
parser = argparse.ArgumentParser()
parser.add_argument('sheet', type=Path)
args = parser.parse_args()
source = args.sheet.resolve(strict=True)
asset_dir = ROOT / 'src' / 'client' / 'assets'
art_dir = ROOT / 'artwork'
asset_dir.mkdir(parents=True, exist_ok=True)
art_dir.mkdir(parents=True, exist_ok=True)
with Image.open(source) as sheet:
    if sheet.size != (1536, 1024):
        raise ValueError(f'Expected the inspected 1536x1024 grid, received {sheet.size}')
    sheet.load()
    target_sheet = art_dir / 'whale-girls-source.png'
    if target_sheet.resolve() != source:
        shutil.copyfile(source, target_sheet)
    generated = {}
    entries = []
    for index, family in enumerate(FAMILIES):
        col, row = index % 4, index // 4
        # Centered 384x384 portrait keeps each face, hair accessory and collar.
        crop = (col * 384, row * 512 + 32, (col + 1) * 384, row * 512 + 416)
        image = sheet.crop(crop).convert('RGB').resize((256, 256), Image.Resampling.LANCZOS)
        path = asset_dir / f'whale-girl-{family}.webp'
        image.save(path, 'WEBP', quality=88, method=6)
        payload = path.read_bytes()
        if len(payload) > 262144:
            raise ValueError(f'{family} exceeds the owned-avatar size limit')
        generated[family] = 'data:image/webp;base64,' + base64.b64encode(payload).decode('ascii')
        entries.append({'family': family, 'file': str(path.relative_to(ROOT)).replace('\\', '/'), 'width': 256, 'height': 256,
                        'bytes': len(payload), 'sha256': hashlib.sha256(payload).hexdigest(), 'sourceCrop': list(crop)})
    (ROOT / 'src' / 'avatar-images.js').write_text('/** Generated by scripts/prepare-avatars.py from the recorded AI artwork; not vendor logos. */\n'
        + 'export const whaleGirlImages = Object.freeze(' + json.dumps(generated, ensure_ascii=False, indent=2) + ');\n', encoding='utf-8', newline='\n')
    manifest = {'sheet': 'artwork/whale-girls-source.png', 'sheetSha256': hashlib.sha256(target_sheet.read_bytes()).hexdigest(), 'width': 1536, 'height': 1024, 'avatars': entries}
    (art_dir / 'avatar-manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', encoding='utf-8', newline='\n')
    print(json.dumps(manifest, ensure_ascii=False, indent=2))
